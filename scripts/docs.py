def check_catalog(r: Report):
    rules = CATALOG_RULES
    ledger_ids = set()
    chain = ROOT / "ledger" / "runs.jsonl"
    if chain.exists():
        ledger_ids = {json.loads(x)["run_id"] for x in chain.read_text().splitlines() if x.strip()}
    strategy_src = "\n".join(p.read_text() for p in
                             (ROOT / "engine/src/parity/strategies").glob("*.py"))
    hyp_ids = {parse(p).meta.get("id") for p in (DOCS / "hypotheses").glob("*.md")}
    seen = {}
    for kind in ("algorithms", "datasets"):
        for p in sorted((CATALOG / kind).glob("*.json")):
            where = p.relative_to(ROOT).as_posix()
            try:
                e = json.loads(p.read_text())
            except json.JSONDecodeError as exc:
                r.err(where, f"not valid JSON: {exc}")
                continue
            if e.get("id") in seen:
                r.err(where, f"duplicate id {e.get('id')} (also {seen[e['id']]})")
            seen[e.get("id")] = where
            if p.stem != e.get("slug"):
                r.err(where, "file name must equal the slug")
            text = json.dumps(e, ensure_ascii=False)
            for ch, name in SCHEMA["style"]["banned_characters"].items():
                if ch in text:
                    r.err(where, f"{name} found")
            if kind == "datasets":
                for key, allowed in (("category", rules["dataset_categories"]),
                                     ("access", rules["dataset_access"])):
                    if e.get(key) not in allowed:
                        r.err(where, f"{key} '{e.get(key)}' not allowed")
                continue
            for key, allowed in (("family", rules["families"]), ("horizon", rules["horizons"])):
                if e.get(key) not in allowed:
                    r.err(where, f"{key} '{e.get(key)}' not allowed")
            for m in e.get("markets", []):
                if m not in rules["markets"]:
                    r.err(where, f"market '{m}' not allowed")
            if e.get("origin", {}).get("type") not in rules["origin_types"]:
                r.err(where, "origin.type not allowed")
            for x in e.get("reported_results", []):
                if not x.get("source_url"):
                    r.err(where, "every reported result needs a source_url")
                if x.get("evidence_type") not in rules["evidence_types"]:
                    r.err(where, f"evidence_type '{x.get('evidence_type')}' not allowed")
            # stage gates: a stage is only allowed when its evidence exists
            rs = e.get("research", {})
            stage = int(rs.get("stage", 1))
            own = "our-idea" in e.get("tags", [])
            benchmark = "benchmark" in e.get("tags", [])
            gates = [
                (2, bool(e.get("reported_results")) or own, "needs at least one reported result"),
                (3, benchmark or rs.get("hypothesis") in hyp_ids,
                 "needs a hypothesis id that exists"),
                (4, bool(rs.get("strategy")) and f'name = "{rs.get("strategy")}"' in strategy_src,
                 "needs a strategy that exists in the engine"),
                (5, bool(rs.get("registrations")) and all(
                    list((ROOT / "registrations").glob(f"{x}-*.json"))
                    for x in rs.get("registrations", [])), "needs a registration file"),
                (6, bool(rs.get("runs")) and set(rs.get("runs", [])) <= ledger_ids,
                 "needs a run that exists in the ledger"),
                (9, rs.get("verdict") in rules["verdicts"], "needs a verdict"),
            ]
            for need, ok, msg in gates:
                if stage >= need and not ok:
                    r.err(where, f"stage {stage} ({STAGE_NAMES[stage - 1]}) {msg}")
            for run in rs.get("runs", []):
                if run not in ledger_ids:
                    r.err(where, f"run {run} is not in the ledger")


