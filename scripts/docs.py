#!/usr/bin/env python3
"""Keeps the docs organised. Standard library only, so it runs anywhere.

    python3 scripts/docs.py check [--base REF] [--suggest]
    python3 scripts/docs.py index
    python3 scripts/docs.py new <type> "<title>" [--tags a,b] [--author name]
    python3 scripts/docs.py fix

The rules live in docs/_system/schema.json. The reasons for them are in
docs/decisions/0004-docs-are-checked-by-a-script.md. In short:

  * the folder a doc sits in decides its type, ID prefix and allowed statuses
  * every doc starts with the same front matter keys, in the same order
  * tags come from a fixed list, related IDs must exist, links and #anchors must resolve
  * plain writing: no em dashes, curly quotes, emojis or stock filler words
  * docs/README.md, docs/TAGS.md and each doc's "Referenced by" block are generated
  * log entries are append-only
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
SCHEMA = json.loads((DOCS / "_system" / "schema.json").read_text())
TYPES: dict = SCHEMA["types"]
GLOSSARY = json.loads((DOCS / "_system" / "glossary.json").read_text())
GLOSSARY_DOC = "REF-0004"
FOLDER_TO_TYPE = {v["folder"]: k for k, v in TYPES.items()}
GENERATED = {ROOT / p for p in SCHEMA["layout"]["generated"]}
GEN_NOTE = "<!-- Generated by scripts/docs.py index. Do not edit by hand. -->"
BL_START = "<!-- backlinks:start (generated by scripts/docs.py) -->"
BL_END = "<!-- backlinks:end -->"
BACKLINK_HEADING = "Referenced by"
TODAY = dt.date.today()

LINK_RE = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
EMOJI_RE = re.compile("[\U0001F000-\U0001FAFF\u2600-\u27BF\uFE0F]")
FENCE_RE = re.compile(r"^(```|~~~)")


# ---------------------------------------------------------------- parsing


@dataclass
class Doc:
    path: Path
    meta: dict = field(default_factory=dict)
    meta_keys: list = field(default_factory=list)
    body: str = ""
    raw: str = ""

    @property
    def rel(self) -> str:
        return self.path.relative_to(ROOT).as_posix()

    @property
    def type(self) -> str | None:
        parts = self.path.relative_to(DOCS).parts
        return FOLDER_TO_TYPE.get(parts[0]) if len(parts) == 2 else None


def parse_value(raw: str):
    raw = raw.strip()
    if raw.startswith("[") and raw.endswith("]"):
        inner = raw[1:-1].strip()
        return [x.strip() for x in inner.split(",")] if inner else []
    return raw


def parse(path: Path) -> Doc:
    text = path.read_text(encoding="utf-8")
    doc = Doc(path=path, raw=text, body=text)
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            for line in text[4:end].splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    doc.meta[k.strip()] = parse_value(v)
                    doc.meta_keys.append(k.strip())
            doc.body = text[end + 5:]
    return doc


def render_front_matter(meta: dict) -> str:
    lines = ["---"]
    for key in SCHEMA["front_matter_keys"]:
        v = meta.get(key, "")
        lines.append(f"{key}: [{', '.join(v)}]" if isinstance(v, list) else f"{key}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def strip_code(text: str) -> str:
    """Blank out fenced blocks and inline code so rules skip them."""
    out, fenced = [], False
    for line in text.splitlines():
        if FENCE_RE.match(line.strip()):
            fenced = not fenced
            out.append("")
            continue
        out.append("" if fenced else re.sub(r"`[^`]*`", "``", line))
    return "\n".join(out)


def strip_backlinks(text: str) -> str:
    return re.sub(re.escape(BL_START) + r".*?" + re.escape(BL_END) + r"\n?", "", text, flags=re.S)


def slugify(heading: str) -> str:
    """GitHub's anchor rule: lowercase, drop punctuation, spaces to hyphens."""
    h = re.sub(r"[`*_~]|<[^>]+>", "", heading.strip().lower())
    h = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", h)
    h = re.sub(r"[^\w\- ]", "", h)
    return h.replace(" ", "-")


def anchors(text: str) -> set[str]:
    seen: dict[str, int] = {}
    out = set()
    for line in strip_code(text).splitlines():
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if m:
            base = slugify(m.group(2))
            n = seen.get(base, 0)
            out.add(base if n == 0 else f"{base}-{n}")
            seen[base] = n + 1
    return out


def headings(text: str, level: int) -> list[str]:
    pat = re.compile(rf"^{'#' * level}\s+(.*?)\s*$")
    return [m.group(1) for line in strip_code(text).splitlines() if (m := pat.match(line))]


# ---------------------------------------------------------------- discovery


def all_markdown() -> list[Path]:
    files = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard",
                            "*.md"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    if not files:  # not a git checkout yet
        files = [p.relative_to(ROOT).as_posix() for p in ROOT.rglob("*.md")
                 if not any(s in p.parts for s in ("node_modules", ".venv", ".git"))]
    return sorted({ROOT / f for f in files if (ROOT / f).exists()})


def typed_docs() -> list[Doc]:
    return [parse(p) for p in all_markdown()
            if DOCS in p.parents and p not in GENERATED and "_system" not in p.parts]


# ---------------------------------------------------------------- checks


class Report:
    def __init__(self):
        self.errors: list[str] = []
        self.notes: list[str] = []

    def err(self, where: str, msg: str):
        self.errors.append(f"{where}: {msg}")


def check_meta(doc: Doc, ids: dict[str, Doc], r: Report):
    where, t = doc.rel, doc.type
    if t is None:
        r.err(where, "docs must sit in one of: " + ", ".join(sorted(FOLDER_TO_TYPE)))
        return
    spec = TYPES[t]
    if doc.meta_keys != SCHEMA["front_matter_keys"]:
        r.err(where, f"front matter keys must be exactly, in order: "
              f"{', '.join(SCHEMA['front_matter_keys'])}")
        return
    m = doc.meta
    if m["type"] != t:
        r.err(where, f"type is '{m['type']}' but the folder says '{t}'")
    if not re.fullmatch(spec["filename"], doc.path.name):
        r.err(where, f"filename does not match the {t} pattern {spec['filename']}")
    if not re.fullmatch(rf"{spec['prefix']}-\d{{4}}", m["id"]):
        r.err(where, f"id must look like {spec['prefix']}-0001")
    elif t != "log" and doc.path.name[:4] != m["id"][-4:]:
        r.err(where, f"id {m['id']} does not match the filename number {doc.path.name[:4]}")
    if m["status"] not in spec["statuses"]:
        r.err(where, f"status '{m['status']}' not allowed for {t}: {', '.join(spec['statuses'])}")
    try:
        created = dt.date.fromisoformat(m["created"])
        updated = dt.date.fromisoformat(m["updated"])
        if updated < created:
            r.err(where, "updated is before created")
        if updated > TODAY + dt.timedelta(days=1):
            r.err(where, "updated is in the future")
        if t == "log" and doc.path.name[:10] != m["created"]:
            r.err(where, "a log file name must start with its created date")
    except (ValueError, TypeError):
        r.err(where, "created and updated must be dates like 2026-10-20")
    for key, allowed, label in (("authors", SCHEMA["authors"], "author"),
                                ("tags", list(SCHEMA["tags"]), "tag")):
        vals = m[key]
        if not isinstance(vals, list) or not vals:
            r.err(where, f"{key} must be a non-empty [list]")
            continue
        for v in vals:
            if v not in allowed:
                r.err(where, f"unknown {label} '{v}' (allowed: see docs/_system/schema.json)")
        if vals != sorted(set(vals)):
            r.err(where, f"{key} must be unique and sorted (run `docs.py fix`)")
    if len(m["tags"]) > 5:
        r.err(where, "use at most 5 tags")
    if not isinstance(m["related"], list):
        r.err(where, "related must be a [list] of IDs")
    else:
        for rid in m["related"]:
            if rid not in ids:
                r.err(where, f"related ID {rid} does not exist")
            elif rid == m["id"]:
                r.err(where, "a doc cannot be related to itself")
    h1 = headings(doc.body, 1)
    if h1 != [m["title"]]:
        r.err(where, f"needs exactly one H1, equal to the title: '# {m['title']}'")
    h2 = [h for h in headings(strip_backlinks(doc.body), 2)]
    missing = [s for s in spec["sections"] if s not in h2]
    if missing:
        r.err(where, f"missing required sections for a {t}: {', '.join(missing)}")


def check_text(path: Path, text: str, r: Report):
    where = path.relative_to(ROOT).as_posix()
    prose = strip_code(text)
    for ch, name in SCHEMA["style"]["banned_characters"].items():
        if ch in prose:
            line = next(i for i, ln in enumerate(prose.splitlines(), 1) if ch in ln)
            r.err(f"{where}:{line}", f"{name} found; use plain punctuation")
    for i, ln in enumerate(prose.splitlines(), 1):
        if EMOJI_RE.search(ln):
            r.err(f"{where}:{i}", "emoji found")
        low = ln.lower()
        for w in SCHEMA["style"]["banned_words"]:
            if re.search(rf"(?<![\w-]){re.escape(w)}(?![\w-])", low):
                r.err(f"{where}:{i}", f"'{w}' is on the plain-language list; say it simply")
    for i, ln in enumerate(text.splitlines(), 1):
        if ln != ln.rstrip():
            r.err(f"{where}:{i}", "trailing whitespace (run `docs.py fix`)")
        if "\t" in ln:
            r.err(f"{where}:{i}", "tab character")
    if not text.endswith("\n") or text.endswith("\n\n"):
        r.err(where, "file must end with exactly one newline (run `docs.py fix`)")


def check_links(path: Path, text: str, r: Report, anchor_cache: dict):
    where = path.relative_to(ROOT).as_posix()
    for i, ln in enumerate(strip_code(text).splitlines(), 1):
        for _label, target in LINK_RE.findall(ln):
            if re.match(r"^(https?|mailto):", target):
                if re.search(r"github\.com/[^/]+/parity/(blob|tree)/", target):
                    r.err(f"{where}:{i}", "link to this repo with a relative path, not a URL")
                continue
            file_part, _, anchor = target.partition("#")
            dest = path if not file_part else (path.parent / file_part).resolve()
            if not dest.exists():
                r.err(f"{where}:{i}", f"broken link: {target}")
                continue
            if ROOT not in dest.parents and dest != ROOT:
                r.err(f"{where}:{i}", f"link leaves the repo: {target}")
            if anchor and dest.suffix == ".md":
                if dest not in anchor_cache:
                    anchor_cache[dest] = anchors(dest.read_text(encoding="utf-8"))
                if anchor not in anchor_cache[dest]:
                    r.err(f"{where}:{i}", f"anchor #{anchor} not found in {file_part or 'this file'}")


def check_layout(r: Report):
    files = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                           cwd=ROOT, capture_output=True, text=True).stdout.split()
    allowed = set(SCHEMA["layout"]["top_level"])
    for top in sorted({f.split("/", 1)[0] for f in files}):
        if top not in allowed:
            r.err(top, "not an allowed top-level entry (see layout.top_level in schema.json)")
    for f in files:
        if f.startswith("docs/") and f.endswith(".md"):
            continue
        if f.startswith("docs/") and not f.startswith("docs/_system/"):
            if not f.startswith(("docs/assets/",)):
                r.err(f, "only markdown, docs/_system and docs/assets belong under docs/")


def check_append_only(base: str, r: Report):
    folder = TYPES["log"]["folder"]
    diff = subprocess.run(["git", "diff", "--unified=0", f"{base}...HEAD", "--",
                           f"docs/{folder}"], cwd=ROOT, capture_output=True, text=True)
    current = None
    for line in diff.stdout.splitlines():
        if line.startswith("--- a/"):
            current = line[6:]
        elif line.startswith("--- /dev/null"):
            current = None
        elif current and line.startswith("-") and not line.startswith("---"):
            if BL_START in line or BL_END in line or line.startswith("-- [") \
                    or line.startswith("-updated:"):
                continue  # generated backlinks and the updated date may change
            r.err(current, "log entries are append-only; add a new entry instead of editing")
            current = None


def suggest_tags(doc: Doc) -> list[str]:
    text = strip_code(doc.body).lower()
    have = set(doc.meta.get("tags") or [])
    out = []
    for tag, spec in SCHEMA["tags"].items():
        hits = sum(len(re.findall(rf"(?<![\w-]){re.escape(k)}", text)) for k in spec["keywords"])
        words = max(len(text.split()), 1)
        if tag not in have and hits >= 3 and hits / words >= 0.004:
            out.append(f"{tag} ({hits} keyword hits)")
    return out


def cmd_check(args) -> int:
    r = Report()
    docs = typed_docs()
    ids: dict[str, Doc] = {}
    for d in docs:
        did = d.meta.get("id")
        if did in ids:
            r.err(d.rel, f"duplicate id {did} (also {ids[did].rel})")
        elif did:
            ids[did] = d
    for d in docs:
        check_meta(d, ids, r)
        check_results(d, r)
    anchor_cache: dict = {}
    for p in all_markdown():
        if p.relative_to(ROOT).as_posix() in SCHEMA["layout"]["unchecked_markdown"]:
            continue
        text = p.read_text(encoding="utf-8")
        check_text(p, text, r)
        check_links(p, text, r, anchor_cache)
    check_layout(r)
    check_glossary(r)
    for path, expected in build_outputs(docs).items():
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            r.err(path.relative_to(ROOT).as_posix(),
                  "generated content is out of date (run `python3 scripts/docs.py index`)")
    if args.base:
        check_append_only(args.base, r)
    if args.suggest:
        for d in docs:
            s = suggest_tags(d)
            if s:
                r.notes.append(f"{d.rel}: consider tags {', '.join(s)}")
    for n in r.notes:
        print(f"note  {n}")
    for e in r.errors:
        print(f"error {e}")
    print(f"\n{len(docs)} docs, {len(all_markdown())} markdown files, {len(r.errors)} problems")
    return 1 if r.errors else 0


# ---------------------------------------------------------------- glossary


def check_glossary(r: Report):
    where = "docs/_system/glossary.json"
    ids = [t["id"] for t in GLOSSARY["terms"]]
    if len(ids) != len(set(ids)):
        r.err(where, "duplicate term ids")
    for t in GLOSSARY["terms"]:
        for key in ("id", "term", "category", "simple", "analogy", "precise"):
            if not str(t.get(key, "")).strip():
                r.err(where, f"term '{t.get('id')}' is missing '{key}'")
        if t.get("category") not in GLOSSARY["categories"]:
            r.err(where, f"term '{t['id']}' has unknown category '{t.get('category')}'")
        for rel in t.get("related", []):
            if rel not in ids:
                r.err(where, f"term '{t['id']}' relates to unknown term '{rel}'")


def glossary_body(title: str) -> str:
    terms = GLOSSARY["terms"]
    by_id = {t["id"]: t for t in terms}
    out = [f"# {title}", "", "## In plain words", "",
           "Every word in this project that sounds like jargon, explained three ways. "
           "**Simple** is how you would explain it to a ten year old. Open **Analogy** for an "
           "everyday comparison and **Precise definition** for the version an economist would "
           "write. The dashboard's Learn tab shows the same entries.", "",
           "## Summary", "",
           f"{len(terms)} terms in {len(GLOSSARY['categories'])} groups. This page is generated "
           "from `docs/_system/glossary.json`; edit that file, not this one, then run "
           "`python3 scripts/docs.py index`.", "",
           "| Group | Terms |", "| --- | --- |"]
    for cat in GLOSSARY["categories"]:
        names = [f"[{t['term']}](#{slugify(t['term'])})" for t in terms if t["category"] == cat]
        out.append(f"| [{cat}](#{slugify(cat)}) | {', '.join(names)} |")
    for cat in GLOSSARY["categories"]:
        out += ["", f"## {cat}"]
        for t in sorted((t for t in terms if t["category"] == cat), key=lambda t: t["term"].lower()):
            out += ["", f"### {t['term']}", "", f"**Simple:** {t['simple']}", "",
                    "<details><summary>Analogy</summary>", "", t["analogy"], "", "</details>", "",
                    "<details><summary>Precise definition</summary>", "", t["precise"], "",
                    "</details>"]
            if t.get("related"):
                links = ", ".join(f"[{by_id[x]['term']}](#{slugify(by_id[x]['term'])})"
                                  for x in t["related"] if x in by_id)
                out += ["", f"Related: {links}"]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- ledger results

RESULTS_RE = re.compile(r"(<!-- results:(RUN-\d{6}) -->\n)(.*?)(<!-- /results -->)", re.S)
LEDGER_DIR = ROOT / "ledger"


def ledger_entry(run_id: str) -> tuple[dict, dict] | None:
    chain = LEDGER_DIR / "runs.jsonl"
    detail = LEDGER_DIR / "runs" / f"{run_id}.json"
    if not chain.exists() or not detail.exists():
        return None
    for line in chain.read_text().splitlines():
        if line.strip():
            e = json.loads(line)
            if e.get("run_id") == run_id:
                return e, json.loads(detail.read_text())
    return None


def _pct(v):
    return "n/a" if v is None else f"{v * 100:.1f}%"


def _num(v):
    return "n/a" if v is None else f"{v:.2f}"


def results_block(run_id: str) -> str:
    found = ledger_entry(run_id)
    if not found:
        return f"Run {run_id} is not in the ledger.\n"
    e, _ = found
    lines = [f"Official run [{run_id}](../../ledger/runs/{run_id}.json) of "
             f"`{e.get('registration')}`, recorded {e.get('recorded_at', '')[:10]}, commit "
             f"`{e.get('git_sha', '')[:8]}`, data fingerprint `{(e.get('data_snapshot') or '')[:12]}`, "
             f"{e.get('trials_counted')} trials counted. Generated from the ledger by "
             "`scripts/docs.py`; it cannot be edited by hand.", "",
             "| Strategy | Sharpe | CAGR | Max drawdown | Deflated Sharpe | Gauntlet | Meets plan |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    res = e.get("results", {})
    for name, r in res.items():
        meets = {True: "yes", False: "no", None: "n/a"}[r.get("meets_registered_criteria")]
        lines.append(f"| `{name}` | {_num(r.get('sharpe'))} | {_pct(r.get('cagr'))} | "
                     f"{_pct(r.get('max_drawdown'))} | {_num(r.get('deflated_sharpe'))} | "
                     f"{r.get('gauntlet')} | {meets} |")
    ids = sorted({t for r in res.values() for t in r.get("tests", {})})
    if ids:
        lines += ["", "| Strategy | " + " | ".join(ids) + " |",
                  "| --- | " + " | ".join("---" for _ in ids) + " |"]
        for name, r in res.items():
            marks = ["pass" if r["tests"].get(t) else "fail" for t in ids]
            lines.append(f"| `{name}` | " + " | ".join(marks) + " |")
    return "\n".join(lines) + "\n"


def _outside_fences(text: str, fn) -> str:
    """Apply fn only to parts of the text that are not inside fenced code blocks."""
    parts = re.split(r"(^\s*(?:```|~~~).*?^\s*(?:```|~~~)[^\n]*$)", text, flags=re.S | re.M)
    return "".join(part if i % 2 else fn(part) for i, part in enumerate(parts))


def fill_results(text: str) -> str:
    return _outside_fences(text, lambda t: RESULTS_RE.sub(
        lambda m: m.group(1) + results_block(m.group(2)) + m.group(4), t))


def check_results(doc: Doc, r: Report):
    cited = []
    _outside_fences(doc.raw, lambda t: cited.extend(m.group(2) for m in RESULTS_RE.finditer(t))
                    or t)
    for run_id in cited:
        if not ledger_entry(run_id):
            r.err(doc.rel, f"cites {run_id}, which is not in the ledger")


# ---------------------------------------------------------------- index


def link(from_path: Path, to: Doc) -> str:
    return Path(os.path.relpath(to.path, from_path.parent)).as_posix()


def outgoing(doc: Doc, by_path: dict[Path, Doc], ids: dict[str, Doc]) -> set[str]:
    out = set(doc.meta.get("related") or [])
    for _l, target in LINK_RE.findall(strip_code(strip_backlinks(doc.body))):
        file_part = target.split("#")[0]
        if file_part and not target.startswith("http"):
            dest = (doc.path.parent / file_part).resolve()
            if dest in by_path and dest != doc.path:
                out.add(by_path[dest].meta.get("id"))
    return {i for i in out if i in ids}


def build_outputs(docs: list[Doc]) -> dict[Path, str]:
    ids = {d.meta["id"]: d for d in docs if d.meta.get("id")}
    by_path = {d.path: d for d in docs}
    order = list(TYPES)

    def key(d: Doc):
        return (order.index(d.type) if d.type in order else 99, d.meta.get("id", ""))

    docs = sorted([d for d in docs if d.meta.get("id") and d.type], key=key)
    out: dict[Path, str] = {}

    # docs/README.md
    idx = DOCS / "README.md"
    lines = [GEN_NOTE, "# Docs index", "",
             "Every document in this folder, grouped by type. How the system works is in "
             f"[the docs guide]({link(idx, ids['GDE-0003'])})" if "GDE-0003" in ids else "",
             "and the tag list is in [TAGS.md](TAGS.md).", ""]
    lines += ["| Type | What it holds | Count |", "| --- | --- | --- |"]
    for t, spec in TYPES.items():
        n = sum(1 for d in docs if d.type == t)
        lines.append(f"| [{t}](#{t}) | {spec['about']} | {n} |")
    open_h = [d for d in docs if d.type == "hypothesis" and d.meta["status"] in
              ("open", "testing")]
    if open_h:
        lines += ["", "## Open questions right now", ""]
        lines += [f"- [{d.meta['id']}: {d.meta['title']}]({link(idx, d)}) ({d.meta['status']})"
                  for d in open_h]
    recent = sorted(docs, key=lambda d: (d.meta["updated"], d.meta["id"]), reverse=True)[:8]
    lines += ["", "## Recently updated", ""]
    lines += [f"- {d.meta['updated']} [{d.meta['id']}: {d.meta['title']}]({link(idx, d)})"
              for d in recent]
    for t in TYPES:
        group = [d for d in docs if d.type == t]
        lines += ["", f"## {t}", ""]
        if not group:
            lines.append("None yet.")
            continue
        lines += ["| ID | Title | Status | Updated | Tags |", "| --- | --- | --- | --- | --- |"]
        for d in group:
            tags = ", ".join(f"[{g}](TAGS.md#{g})" for g in d.meta["tags"])
            lines.append(f"| {d.meta['id']} | [{d.meta['title']}]({link(idx, d)}) | "
                         f"{d.meta['status']} | {d.meta['updated']} | {tags} |")
    out[idx] = "\n".join(x for x in lines if x is not None) + "\n"

    # docs/TAGS.md
    tp = DOCS / "TAGS.md"
    lines = [GEN_NOTE, "# Tags", "",
             "Tags come from a fixed list in `docs/_system/schema.json`. "
             "To add one, change that file in a pull request and say why.", ""]
    for tag, spec in SCHEMA["tags"].items():
        tagged = [d for d in docs if tag in d.meta["tags"]]
        lines += [f"## {tag}", "", spec["about"] + ".", ""]
        lines += [f"- [{d.meta['id']}: {d.meta['title']}]({link(tp, d)})" for d in tagged] or \
            ["Nothing tagged yet."]
        lines.append("")
    out[tp] = "\n".join(lines).rstrip("\n") + "\n"

    # glossary body is generated from glossary.json
    if GLOSSARY_DOC in ids:
        g = ids[GLOSSARY_DOC]
        g.raw = render_front_matter(g.meta) + "\n" + glossary_body(g.meta["title"])
        g.body = g.raw.split("\n---\n", 1)[1]

    # results tables come from the ledger, never from the author
    for d in docs:
        d.raw = fill_results(d.raw)

    # backlinks
    incoming: dict[str, set[str]] = {i: set() for i in ids}
    for d in docs:
        for target in outgoing(d, by_path, ids):
            incoming[target].add(d.meta["id"])
    for d in docs:
        refs = sorted(incoming[d.meta["id"]], key=lambda i: key(ids[i]))
        block = [BL_START, f"## {BACKLINK_HEADING}", ""]
        block += [f"- [{i}: {ids[i].meta['title']}]({link(d.path, ids[i])})" for i in refs] or \
            ["Nothing links here yet."]
        block.append(BL_END)
        body = strip_backlinks(d.raw).rstrip("\n")
        out[d.path] = body + "\n\n" + "\n".join(block) + "\n"
    return out


def cmd_index(_args) -> int:
    changed = 0
    for path, text in build_outputs(typed_docs()).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed += 1
    print(f"index: {changed} files updated")
    return 0


