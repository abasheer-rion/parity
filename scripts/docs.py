# ---------------------------------------------------------------- parsing


@dataclass
class Doc:
    path: Path
    meta: dict = field(default_factory=dict)
    meta_keys: list = field(default_factory=list)
    body: str = ""
    raw: str = ""

    @property
    def rel(self) -> str:
        return self.path.relative_to(ROOT).as_posix()

    @property
    def type(self) -> str | None:
        parts = self.path.relative_to(DOCS).parts
        return FOLDER_TO_TYPE.get(parts[0]) if len(parts) == 2 else None


def parse_value(raw: str):
    raw = raw.strip()
    if raw.startswith("[") and raw.endswith("]"):
        inner = raw[1:-1].strip()
        return [x.strip() for x in inner.split(",")] if inner else []
    return raw


def parse(path: Path) -> Doc:
    text = path.read_text(encoding="utf-8")
    doc = Doc(path=path, raw=text, body=text)
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            for line in text[4:end].splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    doc.meta[k.strip()] = parse_value(v)
                    doc.meta_keys.append(k.strip())
            doc.body = text[end + 5:]
    return doc


def render_front_matter(meta: dict) -> str:
    lines = ["---"]
    for key in SCHEMA["front_matter_keys"]:
        v = meta.get(key, "")
        lines.append(f"{key}: [{', '.join(v)}]" if isinstance(v, list) else f"{key}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def strip_code(text: str) -> str:
    """Blank out fenced blocks and inline code so rules skip them."""
    out, fenced = [], False
    for line in text.splitlines():
        if FENCE_RE.match(line.strip()):
            fenced = not fenced
            out.append("")
            continue
        out.append("" if fenced else re.sub(r"`[^`]*`", "``", line))
    return "\n".join(out)


def strip_backlinks(text: str) -> str:
    return re.sub(re.escape(BL_START) + r".*?" + re.escape(BL_END) + r"\n?", "", text, flags=re.S)


def slugify(heading: str) -> str:
    """GitHub's anchor rule: lowercase, drop punctuation, spaces to hyphens."""
    h = re.sub(r"[`*_~]|<[^>]+>", "", heading.strip().lower())
    h = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", h)
    h = re.sub(r"[^\w\- ]", "", h)
    return h.replace(" ", "-")


def anchors(text: str) -> set[str]:
    seen: dict[str, int] = {}
    out = set()
    for line in strip_code(text).splitlines():
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if m:
            base = slugify(m.group(2))
            n = seen.get(base, 0)
            out.add(base if n == 0 else f"{base}-{n}")
            seen[base] = n + 1
    return out


def headings(text: str, level: int) -> list[str]:
    pat = re.compile(rf"^{'#' * level}\s+(.*?)\s*$")
    return [m.group(1) for line in strip_code(text).splitlines() if (m := pat.match(line))]


# ---------------------------------------------------------------- discovery


def all_markdown() -> list[Path]:
    files = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard",
                            "*.md"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    if not files:  # not a git checkout yet
        files = [p.relative_to(ROOT).as_posix() for p in ROOT.rglob("*.md")
                 if not any(s in p.parts for s in ("node_modules", ".venv", ".git"))]
    return sorted({ROOT / f for f in files if (ROOT / f).exists()})


def typed_docs() -> list[Doc]:
    return [parse(p) for p in all_markdown()
            if DOCS in p.parents and p not in GENERATED and "_system" not in p.parts]


