    if not keys:
        return []
    page = Path(os.path.relpath(REFS_PAGE, d.path.parent)).as_posix()
    return ["## Sources cited", ""] + \
        [f"- [@{k}]({page}#{k}): {short_citation(records[k])}" for k in keys] + [""]


