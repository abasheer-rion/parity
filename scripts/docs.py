def catalog_entries(kind: str) -> list[dict]:
    folder = CATALOG / kind
    return sorted((json.loads(p.read_text()) for p in folder.glob("*.json")),
                  key=lambda e: e["id"]) if folder.exists() else []


def _cell(v) -> str:
    if v is None or v == "":
        return "n/a"
    return str(v).replace("|", "/").replace("\n", " ")


def _pct_or(v):
    return "n/a" if v is None else f"{v * 100:.1f}%"


def _tags_for_algorithm(e: dict) -> list[str]:
    fam = {"carry": "carry", "momentum-trend": "momentum", "event-news": "news",
           "sentiment-alternative-data": "news"}
    mk = {"fx": "fx", "commodities": "commodities", "crypto": "crypto"}
    tags = {"strategy"}
    if e["family"] in fam:
        tags.add(fam[e["family"]])
    tags |= {mk[m] for m in e.get("markets", []) if m in mk}
    if e.get("implementations"):
        tags.add("open-source")
    return sorted(tags)[:5]


def _tags_for_dataset(e: dict) -> list[str]:
    cat = {"fx-prices": "fx", "commodities-energy": "commodities", "news-sentiment": "news",
           "crypto": "crypto", "calendar-consensus": "news", "rates-macro": "economics",
           "equities": "benchmark", "paper-trading": "infra", "factor-research": "method"}
    return sorted({"data", cat.get(e["category"], "data")})


def _href(url: str) -> str:
    """Repo paths in the catalog are relative to the repo root; pages sit two levels down."""
    return url if not url or re.match(r"^[a-z]+:", url) else "../../" + url


def doc_path(kind_folder: str, e: dict) -> Path:
    return DOCS / kind_folder / f"{e['id'][-4:]}-{e['slug']}.md"


