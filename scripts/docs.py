#!/usr/bin/env python3
"""Keeps the docs organised. Standard library only, so it runs anywhere.

    python3 scripts/docs.py check [--base REF] [--suggest]
    python3 scripts/docs.py index
    python3 scripts/docs.py new <type> "<title>" [--tags a,b] [--author name]
    python3 scripts/docs.py fix

The rules live in docs/_system/schema.json. The reasons for them are in
docs/decisions/0004-docs-are-checked-by-a-script.md. In short:

  * the folder a doc sits in decides its type, ID prefix and allowed statuses
  * every doc starts with the same front matter keys, in the same order
  * tags come from a fixed list, related IDs must exist, links and #anchors must resolve
  * plain writing: no em dashes, curly quotes, emojis or stock filler words
  * docs/README.md, docs/TAGS.md, docs/REFERENCES.md and each doc's "Referenced by" block
    are generated
  * every outside source has a record in docs/_system/references.json (built by
    scripts/references.py); prose cites it with [@key] and unknown keys fail the check
  * log entries are append-only
"""

