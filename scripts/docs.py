class Report:
    def __init__(self):
        self.errors: list[str] = []
        self.notes: list[str] = []

    def err(self, where: str, msg: str):
        self.errors.append(f"{where}: {msg}")


def check_meta(doc: Doc, ids: dict[str, Doc], r: Report):
    where, t = doc.rel, doc.type
    if t is None:
        r.err(where, "docs must sit in one of: " + ", ".join(sorted(FOLDER_TO_TYPE)))
        return
    spec = TYPES[t]
    if doc.meta_keys != SCHEMA["front_matter_keys"]:
        r.err(where, f"front matter keys must be exactly, in order: "
              f"{', '.join(SCHEMA['front_matter_keys'])}")
        return
    m = doc.meta
    if m["type"] != t:
        r.err(where, f"type is '{m['type']}' but the folder says '{t}'")
    if not re.fullmatch(spec["filename"], doc.path.name):
        r.err(where, f"filename does not match the {t} pattern {spec['filename']}")
    if not re.fullmatch(rf"{spec['prefix']}-\d{{4}}", m["id"]):
        r.err(where, f"id must look like {spec['prefix']}-0001")
    elif t != "log" and doc.path.name[:4] != m["id"][-4:]:
        r.err(where, f"id {m['id']} does not match the filename number {doc.path.name[:4]}")
    if m["status"] not in spec["statuses"]:
        r.err(where, f"status '{m['status']}' not allowed for {t}: {', '.join(spec['statuses'])}")
    try:
        created = dt.date.fromisoformat(m["created"])
        updated = dt.date.fromisoformat(m["updated"])
        if updated < created:
            r.err(where, "updated is before created")
        if updated > TODAY + dt.timedelta(days=1):
            r.err(where, "updated is in the future")
        if t == "log" and doc.path.name[:10] != m["created"]:
            r.err(where, "a log file name must start with its created date")
    except (ValueError, TypeError):
        r.err(where, "created and updated must be dates like 2026-10-20")
    for key, allowed, label in (("authors", SCHEMA["authors"], "author"),
                                ("tags", list(SCHEMA["tags"]), "tag")):
        vals = m[key]
        if not isinstance(vals, list) or not vals:
            r.err(where, f"{key} must be a non-empty [list]")
            continue
        for v in vals:
            if v not in allowed:
                r.err(where, f"unknown {label} '{v}' (allowed: see docs/_system/schema.json)")
        if vals != sorted(set(vals)):
            r.err(where, f"{key} must be unique and sorted (run `docs.py fix`)")
    if len(m["tags"]) > 5:
        r.err(where, "use at most 5 tags")
    if not isinstance(m["related"], list):
        r.err(where, "related must be a [list] of IDs")
    else:
        for rid in m["related"]:
            if rid not in ids:
                r.err(where, f"related ID {rid} does not exist")
            elif rid == m["id"]:
                r.err(where, "a doc cannot be related to itself")
    h1 = headings(doc.body, 1)
    if h1 != [m["title"]]:
        r.err(where, f"needs exactly one H1, equal to the title: '# {m['title']}'")
    h2 = [h for h in headings(strip_backlinks(doc.body), 2)]
    missing = [s for s in spec["sections"] if s not in h2]
    if missing:
        r.err(where, f"missing required sections for a {t}: {', '.join(missing)}")


def check_text(path: Path, text: str, r: Report):
    where = path.relative_to(ROOT).as_posix()
    prose = strip_code(text)
    for ch, name in SCHEMA["style"]["banned_characters"].items():
        if ch in prose:
            line = next(i for i, ln in enumerate(prose.splitlines(), 1) if ch in ln)
            r.err(f"{where}:{line}", f"{name} found; use plain punctuation")
    for i, ln in enumerate(prose.splitlines(), 1):
        if EMOJI_RE.search(ln):
            r.err(f"{where}:{i}", "emoji found")
        low = ln.lower()
        for w in SCHEMA["style"]["banned_words"]:
            if re.search(rf"(?<![\w-]){re.escape(w)}(?![\w-])", low):
                r.err(f"{where}:{i}", f"'{w}' is on the plain-language list; say it simply")
    for i, ln in enumerate(text.splitlines(), 1):
        if ln != ln.rstrip():
            r.err(f"{where}:{i}", "trailing whitespace (run `docs.py fix`)")
        if "\t" in ln:
            r.err(f"{where}:{i}", "tab character")
    if not text.endswith("\n") or text.endswith("\n\n"):
        r.err(where, "file must end with exactly one newline (run `docs.py fix`)")


def check_links(path: Path, text: str, r: Report, anchor_cache: dict):
    where = path.relative_to(ROOT).as_posix()
    for i, ln in enumerate(strip_code(text).splitlines(), 1):
        for _label, target in LINK_RE.findall(ln):
            if re.match(r"^(https?|mailto):", target):
                if re.search(r"github\.com/[^/]+/parity/(blob|tree)/", target):
                    r.err(f"{where}:{i}", "link to this repo with a relative path, not a URL")
                continue
            file_part, _, anchor = target.partition("#")
            dest = path if not file_part else (path.parent / file_part).resolve()
            if not dest.exists():
                r.err(f"{where}:{i}", f"broken link: {target}")
                continue
            if ROOT not in dest.parents and dest != ROOT:
                r.err(f"{where}:{i}", f"link leaves the repo: {target}")
            if anchor and dest.suffix == ".md":
                if dest not in anchor_cache:
                    anchor_cache[dest] = anchors(dest.read_text(encoding="utf-8"))
                if anchor not in anchor_cache[dest]:
                    r.err(f"{where}:{i}", f"anchor #{anchor} not found in {file_part or 'this file'}")


def check_layout(r: Report):
    files = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                           cwd=ROOT, capture_output=True, text=True).stdout.split()
    allowed = set(SCHEMA["layout"]["top_level"])
    for top in sorted({f.split("/", 1)[0] for f in files}):
        if top not in allowed:
            r.err(top, "not an allowed top-level entry (see layout.top_level in schema.json)")
    for f in files:
        if f.startswith("docs/") and f.endswith(".md"):
            continue
        if f.startswith("docs/") and not f.startswith("docs/_system/"):
            if not f.startswith(("docs/assets/",)):
                r.err(f, "only markdown, docs/_system and docs/assets belong under docs/")


def check_append_only(base: str, r: Report):
    folder = TYPES["log"]["folder"]
    diff = subprocess.run(["git", "diff", "--unified=0", f"{base}...HEAD", "--",
                           f"docs/{folder}"], cwd=ROOT, capture_output=True, text=True)
    current = None
    for line in diff.stdout.splitlines():
        if line.startswith("--- a/"):
            current = line[6:]
        elif line.startswith("--- /dev/null"):
            current = None
        elif current and line.startswith("-") and not line.startswith("---"):
            if BL_START in line or BL_END in line or line.startswith("-- [") \
                    or line.startswith("-updated:") or line.strip() == "-Nothing links here yet.":
                continue  # generated backlinks and the updated date may change
            r.err(current, "log entries are append-only; add a new entry instead of editing")
            current = None


def suggest_tags(doc: Doc) -> list[str]:
    text = strip_code(doc.body).lower()
    have = set(doc.meta.get("tags") or [])
    out = []
    for tag, spec in SCHEMA["tags"].items():
        hits = sum(len(re.findall(rf"(?<![\w-]){re.escape(k)}", text)) for k in spec["keywords"])
        words = max(len(text.split()), 1)
        if tag not in have and hits >= 3 and hits / words >= 0.004:
            out.append(f"{tag} ({hits} keyword hits)")
    return out


def cmd_check(args) -> int:
    r = Report()
    docs = typed_docs()
    ids: dict[str, Doc] = {}
    for d in docs:
        did = d.meta.get("id")
        if did in ids:
            r.err(d.rel, f"duplicate id {did} (also {ids[did].rel})")
        elif did:
            ids[did] = d
    for d in docs:
        check_meta(d, ids, r)
        check_results(d, r)
    anchor_cache: dict = {}
    for p in all_markdown():
        if p.relative_to(ROOT).as_posix() in SCHEMA["layout"]["unchecked_markdown"]:
            continue
        text = p.read_text(encoding="utf-8")
        check_text(p, text, r)
        check_links(p, text, r, anchor_cache)
        check_citations(p, text, r)
    check_layout(r)
    check_references(r)
    check_glossary(r)
    check_catalog(r)
    for path, text in catalog_pages().items():
        if not path.exists():
            r.err(path.relative_to(ROOT).as_posix(), "missing (run `python3 scripts/docs.py index`)")
        elif strip_backlinks(path.read_text()).rstrip("\n") + "\n" != fill_results(text):
            r.err(path.relative_to(ROOT).as_posix(),
                  "differs from its catalog entry; edit the JSON and run `docs.py index`")
    for path, expected in build_outputs(docs).items():
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            r.err(path.relative_to(ROOT).as_posix(),
                  "generated content is out of date (run `python3 scripts/docs.py index`)")
    if args.base:
        check_append_only(args.base, r)
    if args.suggest:
        for d in docs:
            s = suggest_tags(d)
            if s:
                r.notes.append(f"{d.rel}: consider tags {', '.join(s)}")
    for n in r.notes:
        print(f"note  {n}")
    for e in r.errors:
        print(f"error {e}")
    print(f"\n{len(docs)} docs, {len(all_markdown())} markdown files, {len(r.errors)} problems")
    return 1 if r.errors else 0


# ---------------------------------------------------------------- glossary


def check_glossary(r: Report):
    where = "docs/_system/glossary.json"
    ids = [t["id"] for t in GLOSSARY["terms"]]
    if len(ids) != len(set(ids)):
        r.err(where, "duplicate term ids")
    for t in GLOSSARY["terms"]:
        for key in ("id", "term", "category", "simple", "analogy", "precise"):
            if not str(t.get(key, "")).strip():
                r.err(where, f"term '{t.get('id')}' is missing '{key}'")
        if t.get("category") not in GLOSSARY["categories"]:
            r.err(where, f"term '{t['id']}' has unknown category '{t.get('category')}'")
        for rel in t.get("related", []):
            if rel not in ids:
                r.err(where, f"term '{t['id']}' relates to unknown term '{rel}'")


def glossary_body(title: str) -> str:
    terms = GLOSSARY["terms"]
    by_id = {t["id"]: t for t in terms}
    out = [f"# {title}", "", "## In plain words", "",
           "Every word in this project that sounds like jargon, explained three ways. "
           "**Simple** is how you would explain it to a ten year old. Open **Analogy** for an "
           "everyday comparison and **Precise definition** for the version an economist would "
           "write. The dashboard's Learn tab shows the same entries.", "",
           "## Summary", "",
           f"{len(terms)} terms in {len(GLOSSARY['categories'])} groups. This page is generated "
           "from `docs/_system/glossary.json`; edit that file, not this one, then run "
           "`python3 scripts/docs.py index`.", "",
           "| Group | Terms |", "| --- | --- |"]
    for cat in GLOSSARY["categories"]:
        names = [f"[{t['term']}](#{slugify(t['term'])})" for t in terms if t["category"] == cat]
        out.append(f"| [{cat}](#{slugify(cat)}) | {', '.join(names)} |")
    for cat in GLOSSARY["categories"]:
        out += ["", f"## {cat}"]
        for t in sorted((t for t in terms if t["category"] == cat), key=lambda t: t["term"].lower()):
            out += ["", f"### {t['term']}", "", f"**Simple:** {t['simple']}", "",
                    "<details><summary>Analogy</summary>", "", t["analogy"], "", "</details>", "",
                    "<details><summary>Precise definition</summary>", "", t["precise"], "",
                    "</details>"]
            if t.get("related"):
                links = ", ".join(f"[{by_id[x]['term']}](#{slugify(by_id[x]['term'])})"
                                  for x in t["related"] if x in by_id)
                out += ["", f"Related: {links}"]
    return "\n".join(out) + "\n"


