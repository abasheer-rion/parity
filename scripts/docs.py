def cmd_new(args) -> int:
    t = args.type
    if t not in TYPES:
        print(f"type must be one of: {', '.join(TYPES)}")
        return 2
    spec = TYPES[t]
    folder = DOCS / spec["folder"]
    folder.mkdir(exist_ok=True)
    existing = [parse(p).meta.get("id", "") for p in folder.glob("*.md")]
    nums = [int(i[-4:]) for i in existing if re.fullmatch(r"[A-Z]{3}-\d{4}", i)]
    n = max(nums, default=0) + 1
    slug = re.sub(r"[^a-z0-9]+", "-", args.title.lower()).strip("-")
    name = f"{TODAY.isoformat()}-{slug}.md" if t == "log" else f"{n:04d}-{slug}.md"
    path = folder / name
    if path.exists():
        print(f"{path} already exists")
        return 1
    tags = sorted(set(args.tags.split(","))) if args.tags else [t if t in SCHEMA["tags"] else "process"]
    meta = {"id": f"{spec['prefix']}-{n:04d}", "title": args.title, "type": t,
            "status": spec["statuses"][0], "created": TODAY.isoformat(),
            "updated": TODAY.isoformat(), "authors": [args.author], "tags": tags, "related": []}
    body = f"# {args.title}\n\n" + "".join(f"## {s}\n\nTODO\n\n" for s in spec["sections"])
    path.write_text(render_front_matter(meta) + "\n" + body.rstrip("\n") + "\n", encoding="utf-8")
    cmd_index(args)
    print(f"created {path.relative_to(ROOT)} ({meta['id']})")
    return 0


def cmd_fix(args) -> int:
    for p in all_markdown():
        text = p.read_text(encoding="utf-8")
        new = "\n".join(ln.rstrip() for ln in text.splitlines()).rstrip("\n") + "\n"
        if DOCS in p.parents and p not in GENERATED and "_system" not in p.parts:
            d = parse(p)
            if d.meta_keys == SCHEMA["front_matter_keys"]:
                for k in ("tags", "authors"):
                    if isinstance(d.meta[k], list):
                        d.meta[k] = sorted(set(d.meta[k]))
                new = render_front_matter(d.meta) + d.body
                new = "\n".join(ln.rstrip() for ln in new.splitlines()).rstrip("\n") + "\n"
        if new != text:
            p.write_text(new, encoding="utf-8")
            print(f"fixed {p.relative_to(ROOT)}")
    return cmd_index(args)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check")
    c.add_argument("--base", help="git ref to compare against for append-only logs")
    c.add_argument("--suggest", action="store_true", help="print tag suggestions")
    c.set_defaults(func=cmd_check)
    sub.add_parser("index").set_defaults(func=cmd_index)
    n = sub.add_parser("new")
    n.add_argument("type")
    n.add_argument("title")
    n.add_argument("--tags", default="")
    n.add_argument("--author", default="ayan")
    n.set_defaults(func=cmd_new)
    sub.add_parser("fix").set_defaults(func=cmd_fix)
    args = p.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
