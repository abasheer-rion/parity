// Copies the design tokens out of src/ui/tokens.css (the one place they are set) to the
// places that cannot read CSS custom properties:
//   src/ui/tokens.gen.ts          every token resolved to a plain value, for canvas charts,
//                                 share images and the Verify badge SVG
//   ../desktop/electron/tokens.css the token block for the desktop app's own pages
//   ../desktop/electron/tokens.js  plain values for the desktop app's window colours
//   public/offline.html           the token block inline, between tokens:start and tokens:end
//
//   node scripts/tokens.mjs           write the files
//   node scripts/tokens.mjs --check   exit 1 if any is out of date (CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const here = (p) => resolve(import.meta.dirname, "..", p);
const SRC = here("src/ui/tokens.css");
const GEN_TS = here("src/ui/tokens.gen.ts");
const DESKTOP = here("../desktop/electron/tokens.css");
const DESKTOP_JS = here("../desktop/electron/tokens.js");
// Static pages that load before any stylesheet (the offline page the service worker shows)
// carry the token block inline, between these markers.
const INLINE = [here("public/offline.html")];

const css = readFileSync(SRC, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const start = css.indexOf(":root, :root[data-theme=\"dark\"] {");
if (start < 0) throw new Error("tokens.css: no :root block");
let depth = 0, end = start;
for (let i = css.indexOf("{", start); i < css.length; i++) {
  if (css[i] === "{") depth++;
  else if (css[i] === "}" && --depth === 0) { end = i; break; }
}
const block = css.slice(css.indexOf("{", start) + 1, end);

// Declarations in order. Values may hold commas and brackets, so split on ";" at depth 0.
const decls = [];
{
  let d = 0, cur = "";
  for (const ch of block) {
    if (ch === "(") d++;
    if (ch === ")") d--;
    if (ch === ";" && d === 0) { if (cur.trim()) decls.push(cur.trim()); cur = ""; continue; }
    cur += ch;
  }
}
const raw = new Map();
for (const d of decls) {
  const m = d.match(/^--([\w-]+)\s*:\s*([\s\S]+)$/);
  if (m) raw.set(m[1], m[2].trim().replace(/\s+/g, " "));
}

// ---------------------------------------------------------------- resolving values

const hexToRgba = (h) => {
  let s = h.slice(1);
  if (s.length <= 4) s = [...s].map((c) => c + c).join("");
  const n = (i) => parseInt(s.slice(i, i + 2), 16);
  return [n(0), n(2), n(4), s.length === 8 ? n(6) / 255 : 1];
};
const parseColor = (v) => {
  v = v.trim();
  if (/^#[0-9a-f]{3,8}$/i.test(v)) return hexToRgba(v);
  if (v === "transparent") return [0, 0, 0, 0];
  const m = v.match(/^rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)\s*(?:[,/]\s*([\d.]+)(%?))?\s*\)$/);
  if (m) return [+m[1], +m[2], +m[3], m[4] === undefined ? 1 : m[5] ? +m[4] / 100 : +m[4]];
  return null;
};
const fmt = ([r, g, b, a]) => {
  const h = (x) => Math.round(x).toString(16).padStart(2, "0");
  if (a >= 0.999) return `#${h(r)}${h(g)}${h(b)}`;
  return `rgba(${Math.round(r)}, ${Math.round(g)}, ${Math.round(b)}, ${+a.toFixed(3)})`;
};
// color-mix(in srgb, A p%, B): premultiplied mix, as browsers do it.
const mix = (a, p, b) => {
  const [ar, ag, ab, aa] = a, [br, bg, bb, ba] = b;
  const alpha = aa * p + ba * (1 - p);
  if (alpha === 0) return [0, 0, 0, 0];
  const ch = (x, y) => (x * aa * p + y * ba * (1 - p)) / alpha;
  return [ch(ar, br), ch(ag, bg), ch(ab, bb), alpha];
};

const resolved = new Map();
function value(name, seen = new Set()) {
  if (resolved.has(name)) return resolved.get(name);
  if (seen.has(name)) throw new Error(`token loop at --${name}`);
  seen.add(name);
  const v = raw.get(name);
  if (v === undefined) throw new Error(`unknown token --${name}`);
  const out = expand(v, seen);
  resolved.set(name, out);
  return out;
}
function expand(v, seen) {
  // Replace var(--x) with its value, innermost first.
  let s = v, guard = 0;
  while (/var\(--[\w-]+\)/.test(s) && guard++ < 50) s = s.replace(/var\(--([\w-]+)\)/g, (_, n) => value(n, new Set(seen)));
  // Resolve color-mix(in srgb, A p%, B) to one colour.
  guard = 0;
  while (/color-mix\(in srgb,/.test(s) && guard++ < 50) {
    s = s.replace(/color-mix\(in srgb,\s*([^,()]+(?:\([^()]*\))?)\s+([\d.]+)%\s*,\s*([^,()]+(?:\([^()]*\))?)\s*\)/, (all, a, p, b) => {
      const ca = parseColor(a), cb = parseColor(b);
      return ca && cb ? fmt(mix(ca, +p / 100, cb)) : all;
    });
  }
  const c = parseColor(s);
  return c ? fmt(c) : s;
}

const entries = [...raw.keys()].map((k) => [k, value(k)]);

// ---------------------------------------------------------------- outputs

const ts = `// Generated by scripts/tokens.mjs from src/ui/tokens.css. Do not edit; run \`npm run tokens\`.
// Every design token resolved to a plain value, for places that cannot read CSS variables:
// canvas charts, share images rendered at build time and the standalone Verify badge.
// Pages and components use var(--name) through tokens.ts instead.
export const RAW = {
${entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
} as const;

export type TokenName = keyof typeof RAW;
`;

const keep = (k) => !/^(ds-|fs-|fw-)/.test(k) && !["canvas", "side-bg", "bg", "surface", "surface-solid", "hover", "border", "border-2", "grid", "axis", "dot", "text", "text-body", "text-2", "muted", "link", "accent", "accent-hover", "accent-soft", "good", "bad", "benchmark", "radius"].includes(k);
const desktop = `/* Generated by web/scripts/tokens.mjs from web/src/ui/tokens.css. Do not edit; run
   \`npm run tokens\` in web/. The desktop app's own pages (title bar, menu, settings,
   offline page) read the same tokens as the site, resolved to plain values. */
:root {
  color-scheme: dark;
${entries.filter(([k]) => keep(k)).map(([k, v]) => `  --${k}: ${v};`).join("\n")}
}
`;

const desktopJs = `// Generated by web/scripts/tokens.mjs from web/src/ui/tokens.css. Do not edit; run
// \`npm run tokens\` in web/. Plain token values for the desktop app's main process, which
// sets window and view colours before any page (and any CSS) has loaded.
module.exports = {
${entries.filter(([k]) => /^(color-|palette-|font-|type-)/.test(k)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};
`;

const inlineBlock = `:root { ${entries.filter(([k]) => keep(k)).map(([k, v]) => `--${k}: ${v};`).join(" ")} }`;
const withInline = (file) => {
  const now = readFileSync(file, "utf8");
  return now.replace(/(\/\* tokens:start[^*]*\*\/)[\s\S]*?(\s*\/\* tokens:end \*\/)/, (_, a, b) => `${a}\n      ${inlineBlock}${b}`);
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [file, text] of [[GEN_TS, ts], [DESKTOP, desktop], [DESKTOP_JS, desktopJs], ...INLINE.map((f) => [f, withInline(f)])]) {
  const now = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (now === text) continue;
  if (check) { console.error(`out of date: ${file}. Run \`npm run tokens\`.`); stale++; }
  else { writeFileSync(file, text); console.log(`wrote ${file}`); }
}
if (check && !stale) console.log(`tokens: ${entries.length} tokens, generated files up to date`);
process.exit(stale ? 1 : 0);
